export const Spinner = ({ className = "w-4 h-4" }) => <Loader2 className={`animate-spin ${className}`} />;

export function PageLoader({ state, children }) {
  if (state.loading && !state.data)
    return (
      <div className="flex items-center justify-center py-24 text-slate-400">
        <Spinner className="w-6 h-6" />
      </div>
    );
  if (state.error)
    return (
      <div className="card p-6 text-center">
        <AlertTriangle className="w-6 h-6 text-red-500 mx-auto mb-2" />
        <div className="font-medium">{state.error.message}</div>
        {state.error.requestId && <div className="text-xs text-slate-400 mt-1">Request ID: {state.error.requestId}</div>}
        <button className="btn-secondary mt-4" onClick={state.reload}>Retry</button>
      </div>
    );
  return children(state.data);
}

export function AIBanner({ status, message }) {
  if (!status || status === "ok") return null;
  return (
    <div className="flex gap-2 items-start rounded-lg bg-amber-50 border border-amber-200 px-3 py-2 text-sm text-amber-800">
      <Info className="w-4 h-4 mt-0.5 shrink-0" />
      <span>{message || "AI unavailable — showing a rule-based result. Please review it."}</span>
    </div>
  );
}

